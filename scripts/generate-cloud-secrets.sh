#!/usr/bin/env bash
# Creates patient-sys-api/src/main/resources/config/secure-<env>.yaml for a CloudHub
# environment (default: dev). The file holds ciphertext only and is meant to be
# committed; the key is NOT stored anywhere by this script. Put the same key in the
# GitHub Secret MULE_SECURE_KEY.
#
#   scripts/generate-cloud-secrets.sh [env]
#
# Prompts for the key and the database credentials without echoing them, so they do
# not end up in shell history.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
env_name="${1:-dev}"
[[ "$env_name" =~ ^[a-z0-9-]+$ && "$env_name" != "local" && "$env_name" != "test" ]] \
    || { echo "invalid environment: $env_name" >&2; exit 2; }
out="$root/patient-sys-api/src/main/resources/config/secure-$env_name.yaml"

read -r -s -p "Secure-properties key for '$env_name' (16 characters): " key; echo
read -r    -p "Database user: " db_user
read -r -s -p "Database password: " db_password; echo

enc() { "$root/scripts/encrypt-property.sh" "$key" "$1"; }

cat > "$out" <<YAML
# CloudHub '$env_name' database credentials, encrypted with the key held in the
# GitHub Secret MULE_SECURE_KEY. Generated by scripts/generate-cloud-secrets.sh.
db:
  user: "$(enc "$db_user")"
  password: "$(enc "$db_password")"
YAML

echo "wrote $out (ciphertext only; safe to commit)"
