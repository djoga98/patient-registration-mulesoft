#!/usr/bin/env bash
# Generates patient-sys-api/src/main/resources/config/secure-local.yaml from
# infrastructure/.env. The output holds only ciphertext but is still git-ignored:
# every developer encrypts with their own local key.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
env_file="$root/infrastructure/.env"
out="$root/patient-sys-api/src/main/resources/config/secure-local.yaml"

if [[ ! -f "$env_file" ]]; then
    echo "error: $env_file not found; copy infrastructure/.env.example first" >&2
    exit 1
fi

# shellcheck disable=SC1090
set -a; source "$env_file"; set +a
: "${MULE_SECURE_KEY:?MULE_SECURE_KEY missing in infrastructure/.env}"
: "${APP_DB_PASSWORD:?APP_DB_PASSWORD missing in infrastructure/.env}"

enc() { "$root/scripts/encrypt-property.sh" "$MULE_SECURE_KEY" "$1"; }

cat > "$out" <<YAML
# Generated by scripts/generate-local-secrets.sh. Do not commit.
db:
  user: "$(enc patient_app)"
  password: "$(enc "$APP_DB_PASSWORD")"
YAML

echo "wrote $out"
